const money = new Intl.NumberFormat("de-AT", {
  style: "currency",
  currency: "EUR",
  maximumFractionDigits: 0,
});

function t(key) {
  return copy[state.lang][key] || copy.de[key] || key;
}

function price(value) {
  return money.format(value).replace(/\s/g, "");
}

function saveState() {
  localStorage.setItem("naira-cart", JSON.stringify(state.cart));
  localStorage.setItem("naira-gift-wrap", JSON.stringify(state.giftWrap));
  localStorage.setItem("naira-promo", state.promo);
  localStorage.setItem("naira-lang", state.lang);
}

function productById(id) {
  return products.find((product) => product.id === id);
}

function cartItems() {
  return Object.entries(state.cart)
    .map(([id, quantity]) => {
      const product = productById(id);
      return product ? { ...product, quantity } : null;
    })
    .filter(Boolean);
}

function subtotalValue() {
  return cartItems().reduce((sum, item) => sum + item.price * item.quantity, 0);
}

function giftValue() {
  return state.giftWrap && cartItems().length ? 12 : 0;
}

function discountValue() {
  return state.promo === "ALLIN10" ? Math.round(subtotalValue() * 0.1) : 0;
}

function deliveryValue() {
  const subtotal = subtotalValue();
  if (!subtotal || subtotal >= 250) return 0;
  return 18;
}

function totalValue() {
  return subtotalValue() + giftValue() + deliveryValue() - discountValue();
}

function quantityValue() {
  return Object.values(state.cart).reduce((sum, qty) => sum + qty, 0);
}

function showToast(message) {
  els.toast.textContent = message;
  els.toast.classList.add("is-visible");
  window.clearTimeout(showToast.timer);
  showToast.timer = window.setTimeout(() => els.toast.classList.remove("is-visible"), 2300);
}

function applyLanguage() {
  document.documentElement.lang = state.lang;
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.lang === state.lang);
  });
  document.title = `${t("heroTitle")} | ${t("heroSubtitle")}`;
}

function renderCategories() {
  els.categoryRail.innerHTML = categories
    .map(
      (category) => `
        <article class="category-card" style="--category-a: ${category.a}; --category-b: ${category.b};">
          <span>${category.key}</span>
          <h3>${category.title[state.lang]}</h3>
          <p>${category.text[state.lang]}</p>
        </article>
      `
    )
    .join("");
}

function renderProducts() {
  const filtered = products.filter((product) => state.filter === "all" || (product.categories || [product.category]).includes(state.filter));
  els.productGrid.innerHTML = filtered
    .map((product) => {
      const inCart = state.cart[product.id] || 0;
      const sold = Math.max(0, product.initialStock - product.stock);
      const stockWidth = Math.max(8, Math.round((sold / product.initialStock) * 100));
      const mainButton = product.inquiryOnly || product.gated ? t("clubAccess") : t("addToCart");
      const actionAttr = product.inquiryOnly || product.gated ? `data-inquiry-product="${product.id}"` : `data-add="${product.id}"`;
      const disabled = inCart >= product.stock ? "disabled" : "";
      const gallery = product.images || [];

      return `
        <article class="product-card" style="--stage-a: ${product.stageA}; --stage-b: ${product.stageB};">
          <div class="product-stage">
            <img class="product-photo" src="${gallery[0]}" alt="${product.name[state.lang]}" data-product-main="${product.id}" />
          </div>
          <div class="product-gallery" aria-label="Produktbilder">
            ${gallery
              .map(
                (image, index) => `
                  <button class="${index === 0 ? "is-active" : ""}" type="button" data-product-image="${product.id}" data-image-src="${image}" aria-label="Bild ${index + 1}: ${product.name[state.lang]}">
                    <img src="${image}" alt="" />
                  </button>
                `
              )
              .join("")}
          </div>
          <div class="product-body">
            <div class="product-top">
              <div>
                <h3>${product.name[state.lang]}</h3>
                <span class="product-type">${product.type[state.lang]}</span>
              </div>
              <strong class="product-price">${product.inquiryOnly ? `${price(product.price)}+` : price(product.price)}</strong>
            </div>
            <p>${product.desc[state.lang]}</p>
            <div class="benefit-list">
              <span>${t("designed")}</span>
              <span>${t("limited")}</span>
              <span>${t("giftReady")}</span>
            </div>
            <div>
              <div class="stock-row">
                <span>${t("stock").replace("{count}", product.stock)}</span>
                <span>${product.benefits.join(" · ")}</span>
              </div>
              <div class="stock-meter" aria-hidden="true"><span style="--stock-width: ${stockWidth}%;"></span></div>
            </div>
            <div class="product-actions">
              <button class="button button-primary" type="button" ${actionAttr} ${disabled}>${mainButton}</button>
              ${product.inquiryOnly || product.gated ? "" : `<button class="button button-outline" type="button" data-gift-buy="${product.id}">${t("giftBuy")}</button>`}
            </div>
          </div>
        </article>
      `;
    })
    .join("");
}

function renderCart() {
  const lines = cartItems();
  els.cartLines.innerHTML = lines
    .map(
      (item) => `
        <div class="cart-line" style="--stage-a: ${item.stageA}; --stage-b: ${item.stageB};">
          <img class="cart-thumb" src="${item.images[0]}" alt="" loading="lazy" />
          <div>
            <h3>${item.name[state.lang]}</h3>
            <p>${price(item.price)} × ${item.quantity}</p>
          </div>
          <div class="qty" aria-label="Quantity">
            <button type="button" data-decrease="${item.id}">-</button>
            <span>${item.quantity}</span>
            <button type="button" data-increase="${item.id}">+</button>
          </div>
        </div>
      `
    )
    .join("");

  els.emptyCart.hidden = lines.length > 0;
  els.cartCount.textContent = quantityValue();
  els.subtotal.textContent = price(subtotalValue());
  els.giftTotal.textContent = price(giftValue());
  els.discount.textContent = discountValue() ? `-${price(discountValue())}` : price(0);
  els.delivery.textContent = price(deliveryValue());
  els.total.textContent = price(totalValue());
  els.giftWrap.checked = state.giftWrap;
  els.promoInput.value = state.promo;
  els.checkoutOpen.disabled = lines.length === 0;
  const dropStock = products.reduce((sum, item) => sum + item.stock, 0);
  els.dropLeft.textContent = dropStock;
}

function addToCart(id) {
  const product = productById(id);
  const nextQty = (state.cart[id] || 0) + 1;
  if (nextQty > product.stock) return;
  state.cart[id] = nextQty;
  saveState();
  renderCart();
  showToast(t("added").replace("{name}", product.name[state.lang]));
}

function changeQty(id, delta) {
  const product = productById(id);
  const nextQty = (state.cart[id] || 0) + delta;
  if (nextQty <= 0) {
    delete state.cart[id];
  } else {
    state.cart[id] = Math.min(product.stock, nextQty);
  }
  saveState();
  renderCart();
}

function openCart() {
  els.cartDrawer.classList.add("is-open");
  els.cartDrawer.setAttribute("aria-hidden", "false");
  document.body.classList.add("is-locked");
}

function closeCart() {
  els.cartDrawer.classList.remove("is-open");
  els.cartDrawer.setAttribute("aria-hidden", "true");
  document.body.classList.remove("is-locked");
}

function openCheckout() {
  closeCart();
  els.checkoutModal.classList.add("is-open");
  els.checkoutModal.setAttribute("aria-hidden", "false");
  document.body.classList.add("is-locked");
}

function closeCheckout() {
  els.checkoutModal.classList.remove("is-open");
  els.checkoutModal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("is-locked");
}

function saveOrder(formData) {
  const orders = JSON.parse(localStorage.getItem("naira-orders") || "[]");
  const order = {
    id: `NSB-${Date.now().toString().slice(-6)}`,
    language: state.lang,
    createdAt: new Date().toISOString(),
    customer: Object.fromEntries(formData.entries()),
    items: cartItems(),
    giftWrap: state.giftWrap,
    promo: state.promo,
    total: totalValue(),
  };
  orders.push(order);
  localStorage.setItem("naira-orders", JSON.stringify(orders));
  return order;
}

function renderAll() {
  applyLanguage();
  renderCategories();
  renderProducts();
  renderCart();
}

document.addEventListener("click", (event) => {
  const lang = event.target.closest("[data-lang]");
  const filter = event.target.closest("[data-filter]");
  const add = event.target.closest("[data-add]");
  const giftBuy = event.target.closest("[data-gift-buy]");
  const productImage = event.target.closest("[data-product-image]");
  const inquiryProduct = event.target.closest("[data-inquiry-product]");
  const increase = event.target.closest("[data-increase]");
  const decrease = event.target.closest("[data-decrease]");

  if (lang) {
    state.lang = lang.dataset.lang;
    saveState();
    renderAll();
  }

  if (filter) {
    state.filter = filter.dataset.filter;
    document.querySelectorAll("[data-filter]").forEach((button) => {
      const active = button === filter;
      button.classList.toggle("is-active", active);
      button.setAttribute("aria-selected", String(active));
    });
    renderProducts();
  }

  if (add) addToCart(add.dataset.add);

  if (productImage) {
    const card = productImage.closest(".product-card");
    const main = card.querySelector("[data-product-main]");
    main.src = productImage.dataset.imageSrc;
    card.querySelectorAll("[data-product-image]").forEach((button) => button.classList.toggle("is-active", button === productImage));
  }

  if (giftBuy) {
    state.giftWrap = true;
    addToCart(giftBuy.dataset.giftBuy);
    openCart();
  }

  if (inquiryProduct) {
    document.querySelector("#corporate").scrollIntoView({ behavior: "smooth" });
    const product = productById(inquiryProduct.dataset.inquiryProduct);
    document.querySelector("[data-inquiry-form] textarea").value = `Interested in ${product.name.de}`;
  }

  if (increase) changeQty(increase.dataset.increase, 1);
  if (decrease) changeQty(decrease.dataset.decrease, -1);
});

document.querySelectorAll("[data-cart-open]").forEach((button) => button.addEventListener("click", openCart));
document.querySelector("[data-cart-close]").addEventListener("click", closeCart);
els.cartDrawer.addEventListener("click", (event) => {
  if (event.target === els.cartDrawer) closeCart();
});

els.checkoutOpen.addEventListener("click", openCheckout);
document.querySelector("[data-checkout-close]").addEventListener("click", closeCheckout);
els.checkoutModal.addEventListener("click", (event) => {
  if (event.target === els.checkoutModal) closeCheckout();
});

els.giftWrap.addEventListener("change", () => {
  state.giftWrap = els.giftWrap.checked;
  saveState();
  renderCart();
});

document.querySelector("[data-apply-promo]").addEventListener("click", () => {
  const code = els.promoInput.value.trim().toUpperCase();
  if (code === "ALLIN10") {
    state.promo = code;
    els.promoStatus.textContent = t("promoOk");
  } else {
    state.promo = "";
    els.promoStatus.textContent = t("promoBad");
  }
  saveState();
  renderCart();
});

els.checkoutForm.addEventListener("submit", (event) => {
  event.preventDefault();
  const order = saveOrder(new FormData(els.checkoutForm));
  state.cart = {};
  state.giftWrap = false;
  state.promo = "";
  saveState();
  renderCart();
  els.checkoutForm.reset();
  els.checkoutStatus.textContent = t("orderOk").replace("{id}", order.id);
  showToast(t("orderOk").replace("{id}", order.id));
});

els.inquiryForm.addEventListener("submit", (event) => {
  event.preventDefault();
  const inquiries = JSON.parse(localStorage.getItem("naira-inquiries") || "[]");
  inquiries.push({
    language: state.lang,
    createdAt: new Date().toISOString(),
    ...Object.fromEntries(new FormData(els.inquiryForm).entries()),
  });
  localStorage.setItem("naira-inquiries", JSON.stringify(inquiries));
  els.inquiryForm.reset();
  els.inquiryStatus.textContent = t("inquiryOk");
  showToast(t("inquiryOk"));
});

window.addEventListener("keydown", (event) => {
  if (event.key === "Escape") {
    closeCart();
    closeCheckout();
  }
});

window.addEventListener("scroll", () => {
  els.header.classList.toggle("is-scrolled", window.scrollY > 24);
});

renderAll();
